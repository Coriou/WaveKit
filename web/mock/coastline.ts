/** Point in polygon (even-odd within each ring; the rings are separate land pieces, no holes): true on land. */
export function onLand(lat: number, lon: number): boolean {
	return LAND.some(ring => {
		let inside = false
		const n = ring.length / 2
		for (let i = 0, j = n - 1; i < n; j = i++) {
			const xi = ring[2 * i] ?? 0
			const yi = ring[2 * i + 1] ?? 0
			const xj = ring[2 * j] ?? 0
			const yj = ring[2 * j + 1] ?? 0
			if (
				yi > lat !== yj > lat &&
				lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi
			)
				inside = !inside
		}
		return inside
	})
}
