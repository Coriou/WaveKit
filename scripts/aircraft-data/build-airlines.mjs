#!/usr/bin/env node
// Regenerates src/data/airlines.ts from the OpenFlights airline table
// (https://openflights.org/data, Open Database License). Only active airlines
// with a three-letter ICAO designator are kept: the offline airline lookup maps
// a callsign prefix (WKS1234 -> WKS) to the airline.
//
// Usage: node scripts/aircraft-data/build-airlines.mjs [path-to-airlines.dat]

import { readFile, writeFile } from "node:fs/promises"

const SOURCE =
	"https://raw.githubusercontent.com/jpatokal/openflights/master/data/airlines.dat"
const OUT = new URL("../../src/data/airlines.ts", import.meta.url)

function parseCsvLine(line) {
	const out = []
	let cur = ""
	let quoted = false
	for (let i = 0; i < line.length; i++) {
		const c = line[i]
		if (quoted) {
			if (c === '"' && line[i + 1] === '"') {
				cur += '"'
				i++
			} else if (c === '"') quoted = false
			else cur += c
		} else if (c === '"') quoted = true
		else if (c === ",") {
			out.push(cur)
			cur = ""
		} else cur += c
	}
	out.push(cur)
	return out
}

const clean = v =>
	!v || v === "\\N" || v === "-" || v === "N/A" ? "" : v.trim()

const raw = process.argv[2]
	? await readFile(process.argv[2], "utf8")
	: await (await fetch(SOURCE)).text()

const airlines = {}
for (const line of raw.split("\n")) {
	if (!line.trim()) continue
	const [, name, , iata, icao, callsign, country, active] = parseCsvLine(line)
	const code = clean(icao).toUpperCase()
	if (active !== "Y" || !/^[A-Z]{3}$/.test(code) || !clean(name)) continue
	if (airlines[code]) continue
	const iataCode = clean(iata).toUpperCase()
	airlines[code] = [
		clean(name),
		/^[A-Z0-9]{2}$/.test(iataCode) ? iataCode : "",
		clean(callsign).toUpperCase(),
		clean(country),
	]
}

const sorted = Object.fromEntries(
	Object.entries(airlines).sort(([a], [b]) => a.localeCompare(b)),
)
await writeFile(
	OUT,
	`// Generated by scripts/aircraft-data/build-airlines.mjs: do not edit by hand.
// Source: OpenFlights airlines.dat (https://openflights.org/data), Open Database
// License 1.0. Active airlines only, keyed by ICAO designator:
// [name, IATA code, radio callsign, country] ("" when unknown).

/** Airline rows keyed by three-letter ICAO designator. */
// prettier-ignore
export const AIRLINES: Readonly<Record<string, readonly [string, string, string, string]>> = ${JSON.stringify(sorted)}
`,
)
console.log(`${Object.keys(sorted).length} airlines -> ${OUT.pathname}`)
