/**
 * Activity recording DTOs (event foundation batch 1).
 * Structural copies of src/core/activity/types.ts and the public record,
 * query and replay shapes in src/core/activity/storage/contract.ts.
 * WebSocket server messages match the socket wire (`channel: "activity"`),
 * not an internal `{ type: "activity:frame", frame }` wrapper.
 * tests/unit/core/activity/api-types-compat.test.ts fails typecheck on drift.
 */

export type JsonScalar = string | number | boolean | null
export type JsonValue =
	| JsonScalar
	| readonly JsonValue[]
	| { readonly [key: string]: JsonValue }

export interface DecodeField {
	key: string
	label: string
	value: JsonScalar
	unit?: string
}
export interface DecodeProvenance {
	sourceId: string | null
	frequency: {
		hz: number
		basis: "channel" | "probe"
		tuningTrust: "commanded" | "relay" | "unverified"
	} | null
	jobId?: string
	probeId?: string
	channelId?: string
}
export interface DecodeReferences {
	callId?: string
	discoveryId?: string
	observationId?: string
}
export interface DecodePosition {
	lat: number
	lon: number
	altM?: number
}
export interface DecodePresentation {
	entityKey?: string | null
	position?: DecodePosition
	protocol?: string | null
	category?:
		| "aircraft"
		| "marine"
		| "aviation-data"
		| "voice"
		| "paging"
		| "aprs"
		| "sensors"
		| "mesh"
		| "other"
	title?: string | null
	fields?: readonly DecodeField[]
}
export interface DecodeEnvelopeContext {
	/** Allocated once by the ingress owner; never generated by the envelope helper. */
	eventId: string
	receivedAt: Date
	/** Decoder instance ID, matching output.decoder; not the decoder type. */
	decoderId: string
	decoderType?: string
	/** Event-time input binding supplied by its owner, never inferred from data. */
	provenance?: DecodeProvenance
	refs?: DecodeReferences
}

/** A decoder event, including lifecycle/telemetry; not accepted scanner evidence. */
export interface DecodeEnvelope {
	version: 1
	eventId: string
	producedAt: string
	receivedAt: string
	decoderId: string
	decoderType?: string
	outputType: string
	protocol: string | null
	category:
		| "aircraft"
		| "marine"
		| "aviation-data"
		| "voice"
		| "paging"
		| "aprs"
		| "sensors"
		| "mesh"
		| "other"
	entityKey: string | null
	position?: DecodePosition
	title: string | null
	fields: readonly DecodeField[]
	provenance: DecodeProvenance
	refs?: DecodeReferences
	/** Complete JSON projection of decoded data, not original protocol wire output. */
	decodedData: JsonValue
}

export const ACTIVITY_RECORD_VERSION = 1

/** Closed kind union; batch 1 produces the first and last, WG1 adds analog-transmission. */
export type ActivityKind =
	| "decoder-reception"
	| "call-lifecycle"
	| "analog-transmission"
	| "scanner-result"
	| "recording-change"
	| "ingestion-gap"

export type ActivityCategory = DecodeEnvelope["category"]

export interface IngestionGapPayload {
	reason: "rate-limited" | "queue-full" | "write-failed" | "store-paused"
	/** Count of envelopes dropped since the previous gap record. */
	dropped: number
	/** Decoder instance IDs affected, at most 32, sorted. */
	decoderIds: readonly string[]
	fromReceivedAt: string
	toReceivedAt: string
}

/**
 * Payload of an `analog-transmission` record (WG1): one closed squelch-delimited transmission of
 * the live demodulator. The record's eventId equals `transmissionId`.
 */
export interface AnalogTransmissionPayload {
	transmissionId: string
	sourceId: string
	startedAt: string
	endedAt: string
	durationMs: number
	frequency: {
		hz: number
		tuningTrust: "commanded" | "relay" | "unverified"
	} | null
	modulation: "nfm" | "wfm" | "am" | "usb" | "lsb" | "dsb" | "cw" | "raw"
	bandwidthHz: number
	squelchMode: "manual" | "auto"
	thresholdDbfs: number
	peakChannelPowerDbfs: number | null
	meanChannelPowerDbfs: number | null
	closeReason: "squelch" | "retune" | "config" | "stopped" | "max-duration"
}

/** Stored and returned record. commitSeq is assigned by the writer. */
export type ActivityRecord =
	| DecoderReceptionRecord
	| IngestionGapRecord
	| AnalogTransmissionRecord

export interface DecoderReceptionRecord extends ActivityRecordBase {
	kind: "decoder-reception"
	payload: DecodeEnvelope
}

export interface IngestionGapRecord extends ActivityRecordBase {
	kind: "ingestion-gap"
	payload: IngestionGapPayload
}

export interface AnalogTransmissionRecord extends ActivityRecordBase {
	kind: "analog-transmission"
	payload: AnalogTransmissionPayload
}

export interface ActivityRecordBase {
	version: typeof ACTIVITY_RECORD_VERSION
	eventId: string
	/** Decimal string; never a JS number on the wire. */
	commitSeq: string
	producedAt: string
	receivedAt: string
}

/** List/replay summary, at most 4 KiB serialized. */
export interface ActivitySummary {
	eventId: string
	commitSeq: string
	kind: ActivityKind
	producedAt: string
	receivedAt: string
	decoderId: string | null
	sourceId: string | null
	protocol: string | null
	category: ActivityCategory
	frequencyHz: number | null
	entityKey: string | null
	title: string | null
	/** First fields that fit the 4 KiB budget. */
	fields: DecodeEnvelope["fields"]
	position?: DecodeEnvelope["position"]
}

/** ref_type values; ref_value is the matching provenance/refs string. */
export type ActivityRefType =
	| "callId"
	| "discoveryId"
	| "observationId"
	| "jobId"
	| "probeId"
	| "channelId"

/** Query filters shared by REST, facets and WS replay. */
export interface ActivityQuery {
	kinds?: readonly ActivityKind[]
	sourceIds?: readonly string[]
	decoderIds?: readonly string[]
	protocols?: readonly string[]
	categories?: readonly ActivityCategory[]
	frequencyHz?: { min?: number; max?: number }
	/** ISO timestamps; a filter, not chronology authority. */
	producedAt?: { from?: string; to?: string }
	refs?: readonly { type: ActivityRefType; value: string }[]
	entityKey?: string
	/** Plain text, at most 256 UTF-8 bytes; never raw FTS syntax. */
	text?: string
}

export interface ActivitySearchPage {
	items: readonly ActivitySummary[]
	nextPageToken: string | null
	/** Replay cursor positioned at the snapshot's high-water mark H. */
	replayCursor: string
	snapshot: { lowBarrier: string; highWater: string; expiresAt: string }
	searchCoverage: "bounded-projection"
}

export interface ActivityFacetRequest {
	query: ActivityQuery
	dimensions: readonly (
		| "category"
		| "protocol"
		| "decoderId"
		| "sourceId"
		| "kind"
	)[]
}

export interface ActivityFacetResult {
	/** At most 32 values per dimension, count descending then value ascending. */
	facets: Record<string, readonly { value: string | null; count: number }[]>
	/** Rows examined, capped; truncated means counts are lower bounds. */
	scanned: number
	truncated: boolean
	snapshot: { lowBarrier: string; highWater: string }
}

export type ActivityReplayFrame =
	| ActivityReplayRecordsFrame
	| ActivityReplayProgressFrame
	| ActivityReplayResetFrame

export interface ActivityReplayRecordsFrame {
	type: "records"
	items: readonly ActivitySummary[]
	scannedThrough: string
	cursor: string
}

export interface ActivityReplayProgressFrame {
	type: "progress"
	scannedThrough: string
	cursor: string
}

export interface ActivityReplayResetFrame {
	type: "reset"
	reason:
		| "cursor-gap"
		| "cursor-expired"
		| "store-changed"
		| "query-changed"
		| "invalid-cursor"
		| "reader-failed"
}

export interface ActivityStoreStats {
	admitted: number
	committed: number
	duplicates: number
	dropped: Record<
		"rate-limited" | "queue-full" | "store-paused" | "write-failed" | "closed",
		number
	>
	excludedTelemetry: number
	/** Redundant position/presence receptions not stored inside their entity's window (WG1). Optional for older cores. */
	coalescedPositions?: number
	queueDepth: number
	queueBytes: number
	dbBytes: number
	walBytes: number
	rows: number
	oldestReceivedAt: string | null
	pruneWatermark: string
	paused: boolean
	/** `stopped` after the writer exits or a write times out. No restart in this batch. */
	writer: "running" | "stopped"
}

/** Client → server. `cursor` omitted starts live at the current committed max. */
export interface ActivitySubscribeMessage {
	type: "activity:subscribe"
	id: string
	query: ActivityQuery
	cursor?: string
}

export interface ActivityUnsubscribeMessage {
	type: "activity:unsubscribe"
	id: string
}

export type ActivityClientMessage =
	| ActivitySubscribeMessage
	| ActivityUnsubscribeMessage

/**
 * Server → client. One JSON object per replay frame or subscription notice.
 * `data` carries the subscription id; there is no `activity:frame` wrapper.
 */
export interface ActivityRecordsMessage {
	type: "activity:records"
	channel: "activity"
	data: {
		id: string
		items: readonly ActivitySummary[]
		scannedThrough: string
		cursor: string
	}
}

export interface ActivityProgressMessage {
	type: "activity:progress"
	channel: "activity"
	data: {
		id: string
		scannedThrough: string
		cursor: string
	}
}

export interface ActivityResetMessage {
	type: "activity:reset"
	channel: "activity"
	data: {
		id: string
		reason: ActivityReplayResetFrame["reason"]
	}
}

export interface ActivitySubscribedMessage {
	type: "activity:subscribed"
	channel: "activity"
	data: { id: string }
}

export interface ActivityUnsubscribedMessage {
	type: "activity:unsubscribed"
	channel: "activity"
	data: { id: string }
}

/** Overflow close. `cursors` is the last delivered cursor per subscription id. */
export interface ActivityClosedMessage {
	type: "activity:closed"
	channel: "activity"
	data: {
		reason: "resumable"
		cursors: Readonly<Record<string, string>>
	}
}

export interface ActivityErrorMessage {
	type: "error"
	channel: "activity"
	data: {
		code: string
		message: string
		id?: string
	}
}

export type ActivityServerMessage =
	| ActivityRecordsMessage
	| ActivityProgressMessage
	| ActivityResetMessage
	| ActivitySubscribedMessage
	| ActivityUnsubscribedMessage
	| ActivityClosedMessage
	| ActivityErrorMessage
