/**
 * Activity store lifecycle in `GET /api/activity/status` (`stats.lifecycle`). `opening`: the
 * first open is running; `retrying`: an open failed and the next attempt is at
 * `nextAttemptAt`; `available`: the store is open; `unavailable`: a failure that a retry
 * cannot fix (no node:sqlite, a foreign schema). `reason` is a code, never a message.
 * Optional for older cores.
 */
export type ActivityLifecycleState =
	| "opening"
	| "retrying"
	| "available"
	| "unavailable"

export type ActivityLifecycleReason =
	| "ACTIVITY_UNAVAILABLE"
	| "ACTIVITY_STORE_LOCKED"
	| "ACTIVITY_SCHEMA_MISMATCH"
	| "ACTIVITY_OPEN_TIMEOUT"

export interface ActivityLifecycleStatus {
	state: ActivityLifecycleState
	/** The last failed attempt's code; null once available or before any failure. */
	reason: ActivityLifecycleReason | null
	/** Open attempts started this session, the running one included. */
	attempts: number
	/** ISO time of the next attempt while `retrying`, else null. */
	nextAttemptAt: string | null
	/** Receptions and transmissions dropped while the store was not open. */
	droppedWhileClosed: number
}

export interface ActivityStoreStats {
	admitted: number
	committed: number
	duplicates: number
	dropped: Record<
		"rate-limited" | "queue-full" | "store-paused" | "write-failed" | "closed",
		number
	>
	excludedTelemetry: number
	/** Redundant position/presence receptions not stored inside their entity's window (WG1). Optional for older cores. */
	coalescedPositions?: number
	queueDepth: number
	queueBytes: number
	dbBytes: number
	walBytes: number
	rows: number
	oldestReceivedAt: string | null
	pruneWatermark: string
	paused: boolean
	/** `stopped` after the writer exits or a write times out. No restart in this batch. */
	writer: "running" | "stopped"
	/** WG3: retention policy and per-share usage. Optional for older cores. */
	retention?: ActivityRetentionStats
	/** WG3: Meshtastic flood copies not stored (not a loss). Optional for older cores. */
	floodCopies?: number
	/**
	 * Store lifecycle. While `state` is not `available` the counters above are zero and
	 * `writer` is `stopped`. Optional for older cores.
	 */
	lifecycle?: ActivityLifecycleStatus
}

/**
 * WG3 retention policy. `fair-share` water-fills the row and byte caps across shares (decoder
 * feeds); `oldest-first` removes the oldest rows of all feeds alike. Age pruning is the same.
 */
export type ActivityRetentionPolicy = "fair-share" | "oldest-first"

/** One share: `decoder:<decoderId>`, or `kind:<kind>` for rows without a decoder. */
export interface ActivityRetentionShare {
	key: string
	rows: number
	/** Sum of stored record bytes (not on-disk bytes). */
	bytes: number
	/** ISO receivedAt of the share's oldest stored row; null when unknown. */
	oldestReceivedAt: string | null
}

export interface ActivityRetentionStats {
	/** The configured policy. */
	policy: ActivityRetentionPolicy
	/** The policy in force: `oldest-first` when fair-share fell back for this session. */
	effective: ActivityRetentionPolicy
	/** Largest first by rows, then key ascending; at most 64. */
	shares: readonly ActivityRetentionShare[]
	/** True when more than 64 shares exist. */
	sharesTruncated: boolean
	/**
	 * Cap steps this session outside the fair floor: an oldest-first prefix because no share
	 * was above the fair level (req 1.12), or the single-row step that deletes the oldest row
	 * of the over-level share with the largest excess when no fair delete fits (req 1.5).
	 * 0 under `oldest-first`.
	 */
	prefixFallbackSteps: number
}

